const knownPageMatchers = knownPagePatterns.map((pattern) => new RegExp(
  `^${pattern.split("/").map((part) => (part.startsWith(":") ? "[^/]+" : part.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"))).join("/")}/?$`,
));

/** Whether the app has a page at this path (the query string aside). */
export function isKnownPagePath(pathname: string) {
  return knownPageMatchers.some((matcher) => matcher.test(pathname));
}
